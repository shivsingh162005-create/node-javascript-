// challange : Dog age to Human Age calculator

// To create a dog age to human age calculator, you can use the following 
// Human Age = (Dog age - 2) * 4 + 21
// Alert = your dog is ____________ Years old in human years.

// Function to calculate human age from dog age:

let dogAge = prompt("how old is your dog age in years?"); // Prompt user for dog's age
let humanAge = (dogAge - 2) * 4 + 21; // Calculate human age using the formula

alert("Your dog is " + humanAge + " years old in human years."); // Display the result in an alert